const DICTS: Record<Lang, Record<MessageKey, string>> = { en, zh };

const STORAGE_KEY = "clovergo.lang";

function readStored(): Lang {
  try {
    const value = window.localStorage.getItem(STORAGE_KEY);
    return value === "zh" || value === "en" ? value : "zh";
  } catch {
    return "zh";
  }
}

let current: Lang = readStored();
const listeners = new Set<() => void>();

function applyDocument(lang: Lang): void {
  try {
    document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
    document.title = DICTS[lang]["app.title"];
  } catch {
    // Non-browser environments have no document; nothing to update.
  }
}

applyDocument(current);

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  try {
    window.localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // Storage may be unavailable; the switch still applies for this session.
  }
  applyDocument(lang);
  listeners.forEach((listener) => listener());
}

/** Locale for Intl formatting (dates, numbers) that matches the UI language. */
export function locale(): string {
  return current === "zh" ? "zh-CN" : "en-US";
}

export function isMessageKey(key: string): key is MessageKey {
  return Object.prototype.hasOwnProperty.call(en, key);
}

export type Vars = Record<string, string | number>;

/** Translate a key in the current language, replacing `{name}` placeholders. */
export function t(key: MessageKey, vars?: Vars): string {
  const template = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

/**
 * Like t(), but placeholders may be React nodes (for example a highlighted
 * query). Returns keyed fragments, safe to render as children.
 */
export function tx(key: MessageKey, vars: Record<string, ReactNode>): ReactNode[] {
  const template = DICTS[current][key] ?? en[key] ?? key;
  return template.split(/(\{\w+\})/g).map((part, index) => {
    const name = /^\{(\w+)\}$/.exec(part)?.[1];
    const node = name && name in vars ? vars[name] : part;
    return createElement(Fragment, { key: index }, node);
  });
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** The current language; re-renders the caller when it changes. */
export function useLang(): [Lang, (lang: Lang) => void] {
  const lang = useSyncExternalStore(subscribe, getLang, getLang);
  return [lang, setLang];
}
